    public static IReadOnlyList<BusinessProfileDefinition> All => Profiles;

    public static BusinessProfileDefinition Get(BusinessProfileId id) =>
        Profiles.FirstOrDefault(p => p.Id == id) ?? throw new KeyNotFoundException($"Unknown business profile {id}.");

    public static string ResourceKindName(ResourceKind kind) => kind switch
    {
        ResourceKind.Room => "Oda",
        ResourceKind.Device => "Cihaz",
        ResourceKind.Chair => "Koltuk",
        ResourceKind.TreatmentUnit => "Ünit",
        ResourceKind.ServiceBay => "Lift / Bölme",
        ResourceKind.Studio => "Stüdyo / Salon",
        ResourceKind.Equipment => "Ekipman",
        _ => "Diğer",
    };

    private static HashSet<ProfileFeature> Set(params ProfileFeature[] features) => [.. features];
